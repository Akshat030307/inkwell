  // Keep the root a sequence of blocks: stray text or inline elements typed
  // directly into it are gathered into paragraphs.
  function normalizeRoot() {
    if (!docEl.firstChild || (docEl.childNodes.length === 1 && docEl.firstChild.nodeName === 'BR')) {
      docEl.innerHTML = '<p><br></p>';
      placeCaret(docEl.firstChild);
      return false;
    }
    let group = null, moved = false;
    // Chrome sometimes builds a list inside the paragraph it converted:
    // <p><ul>…</ul></p>. Lift such lists out of their paragraph.
    for (const p of $$('p', docEl)) {
      const lists = Array.from(p.children).filter((c) => c.tagName === 'UL' || c.tagName === 'OL');
      if (!lists.length) continue;
      const onlyLists = Array.from(p.childNodes).every((c) =>
        lists.includes(c) || c.nodeName === 'BR' || (c.nodeType === 3 && !/\S/.test(c.data)));
      if (onlyLists) { p.replaceWith(...lists); moved = true; }
    }
    for (const n of Array.from(docEl.childNodes)) {
      const isText = n.nodeType === 3;
      if (isText && !/\S/.test(n.data) && !group) {
        const s = getSelection();
        if (!(s.rangeCount && s.anchorNode === n)) { n.remove(); moved = true; }
        continue;
      }
      const inline = isText || (n.nodeType === 1 && !BLOCK_RE.test(n.tagName));
      if (inline) {
        if (!group) { group = document.createElement('p'); docEl.insertBefore(group, n); }
        group.appendChild(n);
        moved = true;
      } else {
        group = null;
      }
    }
    return moved;
  }

  const LEGACY_PT = { 1: 8, 2: 10, 3: 12, 4: 14, 5: 18, 6: 24, 7: 36 };

  // execCommand('fontSize') only knows HTML sizes 1-7. Inkwell asks for 7 and
  // then rewrites the result to the real point size; <font> tags from other
  // browsers or pasted content become styled spans.
  function fixLegacyFonts() {
    for (const s of $$('span[style*="xxx-large"]', docEl)) {
      if (s.style.fontSize === 'xxx-large') s.style.fontSize = (state.pendingSize || 36) + 'pt';
    }
    const fonts = $$('font', docEl);
    if (!fonts.length) return;
    keepingSelection(() => {
      for (const f of fonts) {
        const span = document.createElement('span');
        if (f.color) span.style.color = f.color;
        if (f.face) span.style.fontFamily = f.face;
        if (f.size) span.style.fontSize = (f.size === '7' && state.pendingSize ? state.pendingSize : LEGACY_PT[f.size] || 11) + 'pt';
        if (f.style.cssText) span.style.cssText += f.style.cssText;
        while (f.firstChild) span.appendChild(f.firstChild);
        f.replaceWith(span);
      }
      return true;
    });
  }

  // ------------------------------------------------------------ paragraph helpers

  function selectedBlocks() {
    const s = getSelection();
    if (!s.rangeCount) return [];
    const r = s.getRangeAt(0);
    if (!inDoc(r.commonAncestorContainer)) return [];
    const start = closestBlock(r.startContainer);
    let blocks = $$(LEAF_BLOCK, docEl).filter((b) =>
      r.intersectsNode(b) && !b.querySelector(LEAF_BLOCK) && !b.closest('.toc') &&
      // A selection ending at offset 0 of a block does not really include it.
      !(b !== start && !r.collapsed && r.endOffset === 0 && b.contains(r.endContainer)));
    if (!blocks.length) {
      const cell = closestIn(r.startContainer, 'td,th');
      if (cell) {
        // Text sitting directly in a table cell: give it a paragraph first.
        const p = document.createElement('p');
        keepingSelection(() => {
          while (cell.firstChild) p.appendChild(cell.firstChild);
          cell.appendChild(p);
          return true;
        });
        blocks = [p];
      } else if (start) {
        blocks = [start];
      }
    }
    return blocks;
  }

  function styleKey(block) {
    if (!block) return 'normal';
    if (block.dataset && block.dataset.style) return block.dataset.style;
    const tag = block.tagName.toLowerCase();
    if (tag === 'p') return block.classList.contains('title') ? 'title' : 'normal';
    if (tag === 'blockquote') return 'quote';
    return STYLE_SPEC[tag] ? tag : 'normal';
  }

  // Apply a paragraph style: a built-in key (normal, title, h1...) or the id
  // of a custom style, which is a <p data-style="id">.
  function setBlockStyle(name) {
    const [tag, cls] = STYLE_SPEC[name] || ['p', ''];
    const custom = STYLE_SPEC[name] ? '' : name;
    const blocks = selectedBlocks();
    const sel = saveSel();
    for (const b of blocks) {
      if (b.tagName === 'LI') continue;
      if (styleKey(b) === name) continue;
      const n = document.createElement(tag);
      if (cls) n.className = cls;
      if (custom) n.dataset.style = custom;
      n.style.cssText = b.style.cssText;
      while (b.firstChild) n.appendChild(b.firstChild);
      b.replaceWith(n);
    }
    restoreSel(sel);
  }

  function indentBlocks(dir) {
    const s = getSelection();
    if (s.rangeCount && closestIn(s.anchorNode, 'li')) {
      exec(dir > 0 ? 'indent' : 'outdent');
      return;
    }
    for (const b of selectedBlocks()) {
      const next = Math.max(0, (parseFloat(b.style.marginLeft) || 0) + dir * 48);
      b.style.marginLeft = next ? next + 'px' : '';
    }
  }

