  function restoreSel(sel) {
    if (!sel) return;
    const a = nodeAt(sel.a), b = nodeAt(sel.b);
    if (!a || !b) return;
    try {
      const r = document.createRange();
      r.setStart(a, Math.min(sel.ao, nodeLen(a)));
      r.setEnd(b, Math.min(sel.bo, nodeLen(b)));
      setRange(r);
    } catch (e) { /* the old selection no longer fits this DOM */ }
  }

  // Run a DOM move without losing the caret: moved nodes keep their identity,
  // so the original boundary nodes and offsets are still valid afterwards.
  function keepingSelection(fn) {
    const s = getSelection();
    const r = s.rangeCount && inDoc(s.anchorNode) ? s.getRangeAt(0) : null;
    const keep = r && [r.startContainer, r.startOffset, r.endContainer, r.endOffset];
    const changed = fn();
    if (changed && keep && inDoc(keep[0]) && inDoc(keep[2])) {
      try {
        const nr = document.createRange();
        nr.setStart(keep[0], keep[1]);
        nr.setEnd(keep[2], keep[3]);
        setRange(nr);
      } catch (e) { /* ignore */ }
    }
  }

