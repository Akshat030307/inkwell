  function textIndex() {
    const walker = document.createTreeWalker(docEl, NodeFilter.SHOW_TEXT);
    const nodes = [];
    let text = '', lastBlock = null, n;
    while ((n = walker.nextNode())) {
      if (n.parentElement.closest('.toc')) continue;
      const block = closestBlock(n) || n.parentElement;
      // Separate paragraphs so matches never run across them.
      if (lastBlock && block !== lastBlock) text += '\u0000';
      lastBlock = block;
      nodes.push({ n, start: text.length });
      text += n.data;
    }
    return { nodes, text };
  }

  function locate(nodes, pos) {
    let lo = 0, hi = nodes.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (nodes[mid].start <= pos) lo = mid; else hi = mid - 1;
    }
    return nodes[lo];
  }

  function search(keepIndex) {
    const q = findInput.value;
    const matchCase = $('#matchCase').checked;
    find.ranges = [];
    find.snippets = [];
    if (q) {
      const { nodes, text } = textIndex();
      const hay = matchCase ? text : text.toLowerCase();
      const needle = matchCase ? q : q.toLowerCase();
      let i = hay.indexOf(needle);
      while (i !== -1 && nodes.length) {
        const a = locate(nodes, i), b = locate(nodes, i + needle.length - 1);
        const r = document.createRange();
        r.setStart(a.n, i - a.start);
        r.setEnd(b.n, i + needle.length - b.start);
        find.ranges.push(r);
        const from = Math.max(0, text.lastIndexOf('\u0000', i) + 1, i - 40);
        let to = text.indexOf('\u0000', i + needle.length);
        if (to < 0 || to > i + needle.length + 60) to = i + needle.length + 60;
        find.snippets.push([text.slice(from, i), text.slice(i, i + needle.length), text.slice(i + needle.length, to)]);
        i = hay.indexOf(needle, i + needle.length);
      }
    }
    find.index = find.ranges.length ? (keepIndex ? Math.min(find.index, find.ranges.length - 1) : -1) : -1;
    paintFind();
  }

  function paintFind() {
    const n = find.ranges.length;
    $('#findCount').textContent = !findInput.value ? '' : n ? (find.index >= 0 ? (find.index + 1) + ' of ' + n : n + ' result' + (n === 1 ? '' : 's')) : 'No results';
    $('#navResults').innerHTML = find.snippets.slice(0, 200).map((s, i) =>
      '<button class="nav-result' + (i === find.index ? ' on' : '') + '" data-result="' + i + '">' +
      escHtml(s[0]) + '<mark>' + escHtml(s[1]) + '</mark>' + escHtml(s[2]) + '</button>').join('');
    if (!window.CSS || !CSS.highlights || typeof Highlight === 'undefined') return;
    CSS.highlights.set('find-all', new Highlight(...find.ranges));
    const cur = find.ranges[find.index];
    if (cur) CSS.highlights.set('find-current', new Highlight(cur)); else CSS.highlights.delete('find-current');
  }

  function gotoMatch(i) {
    find.index = i;
    const r = find.ranges[i];
    if (!r) return;
    savedRange = r.cloneRange();
    const el = elementOf(r.startContainer);
    if (el) el.scrollIntoView({ block: 'center', behavior: 'smooth' });
    paintFind();
  }

  function stepFind(dir) {
    if (!find.ranges.length) search();
    const n = find.ranges.length;
    if (!n) return;
    gotoMatch(find.index < 0 ? (dir > 0 ? 0 : n - 1) : (find.index + dir + n) % n);
  }

