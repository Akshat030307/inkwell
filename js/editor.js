  // ------------------------------------------------------------ sanitizing

  const KEEP_TAGS = new Set(['P', 'H1', 'H2', 'H3', 'H4', 'H5', 'H6', 'B', 'STRONG', 'I', 'EM', 'U', 'S', 'STRIKE', 'DEL',
    'INS', 'SUB', 'SUP', 'A', 'BR', 'UL', 'OL', 'LI', 'TABLE', 'THEAD', 'TBODY', 'TFOOT', 'TR', 'TD', 'TH', 'IMG', 'SPAN',
    'BLOCKQUOTE', 'DIV', 'HR', 'PRE', 'FONT', 'CODE', 'MARK']);
  const DROP_TAGS = new Set(['SCRIPT', 'STYLE', 'IFRAME', 'OBJECT', 'EMBED', 'META', 'LINK', 'HEAD', 'TITLE', 'NOSCRIPT',
    'TEMPLATE', 'SVG', 'MATH', 'FORM', 'INPUT', 'BUTTON', 'SELECT', 'TEXTAREA', 'VIDEO', 'AUDIO', 'CANVAS']);
  const STYLE_PROPS = ['font-weight', 'font-style', 'text-decoration', 'text-decoration-line', 'color', 'background-color',
    'font-size', 'font-family', 'text-align', 'vertical-align', 'line-height', 'margin-left', 'margin-right', 'margin-top',
    'margin-bottom', 'text-indent', 'border-top', 'border-bottom', 'border-left', 'border-right'];
  const KEEP_CLASSES = ['title', 'caption', 'page-break', 'column-break', 'section', 'toc', 'comment', 'tc'];
  const KEEP_DATA = ['cols', 'cid', 'author', 'date', 'style', 'bullet', 'format', 'wrap', 'level'];
  const CONTAINERS = /^(DIV|UL|OL|TABLE|TBODY|THEAD|TFOOT|TR|BLOCKQUOTE)$/;

  // Keep only the structure and formatting Inkwell understands. Foreign HTML
  // has its source whitespace collapsed; Inkwell's own (saved documents)
  // keeps it, along with Inkwell's own classes and data attributes.
  function sanitize(html, own = false) {
    const src = new DOMParser().parseFromString(html, 'text/html').body;
    const out = document.createElement('div');
    const walk = (from, to) => {
      for (const n of Array.from(from.childNodes)) {
        if (n.nodeType === 3) {
          let t = n.data;
          if (!own) {
            t = t.replace(/[\t\n\r ]+/g, ' ');
            const blockSibling = [n.previousSibling, n.nextSibling].some((s) => !s || (s.nodeType === 1 && BLOCK_RE.test(s.tagName)));
            if (t === ' ' && (to === out || CONTAINERS.test(to.tagName) || blockSibling)) continue;
          }
          if (t) to.appendChild(document.createTextNode(t));
          continue;
        }
        if (n.nodeType !== 1 || DROP_TAGS.has(n.tagName)) continue;
        if (!KEEP_TAGS.has(n.tagName)) { walk(n, to); continue; }
        const el = document.createElement(n.tagName === 'FONT' ? 'span' : n.tagName.toLowerCase());
        if (n.tagName === 'FONT') {
          if (n.getAttribute('color')) el.style.color = n.getAttribute('color');
          if (n.getAttribute('face')) el.style.fontFamily = n.getAttribute('face');
        }
        const href = n.getAttribute('href');
        if (el.tagName === 'A' && href && /^(https?:|mailto:|#)/i.test(href.trim())) el.setAttribute('href', href.trim());
        const srcAttr = n.getAttribute('src');
        if (el.tagName === 'IMG') {
          if (!srcAttr || !/^(data:image\/(png|jpeg|gif|bmp);|https?:)/i.test(srcAttr)) continue;
          el.setAttribute('src', srcAttr);
          for (const a of ['width', 'height']) if (/^\d+$/.test(n.getAttribute(a) || '')) el.setAttribute(a, n.getAttribute(a));
          el.setAttribute('alt', n.getAttribute('alt') || '');
        }
        for (const a of ['colspan', 'rowspan']) if (/^\d+$/.test(n.getAttribute(a) || '')) el.setAttribute(a, n.getAttribute(a));
        for (const p of STYLE_PROPS) {
          const v = n.style.getPropertyValue(p);
          if (v && !/url\(|expression/i.test(v)) el.style.setProperty(p, v);
        }
        const classes = Array.from(n.classList).filter((c) => (own ? KEEP_CLASSES : ['title', 'caption']).includes(c));
        if (classes.length) el.className = classes.join(' ');
        if (own) {
          for (const d of KEEP_DATA) if (n.dataset[d] !== undefined) el.dataset[d] = String(n.dataset[d]).slice(0, 200);
        }
        if (/page-break|column-break|toc/.test(el.className)) el.contentEditable = 'false';
        walk(n, el);
        to.appendChild(el);
      }
    };
    walk(src, out);
    return out.innerHTML;
  }

  function textToHtml(text) {
    const lines = text.replace(/\r\n?/g, '\n').split('\n');
    return lines.map((l) => '<p>' + (l ? escHtml(l) : '<br>') + '</p>').join('');
  }

