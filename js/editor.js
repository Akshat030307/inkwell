  async function openFile(file) {
    const ext = (file.name.split('.').pop() || '').toLowerCase();
    const title = file.name.replace(/\.[^.]+$/, '');
    try {
      let data;
      if (ext === 'docx') {
        const r = await Docx.read(await file.arrayBuffer());
        data = Object.assign(r, { title: r.title || title });
      } else if (ext === 'html' || ext === 'htm') {
        data = { html: sanitize(await file.text()), title };
      } else {
        data = { html: textToHtml(await file.text()), title };
      }
      emit('beforeOpen', data);
      loadDocument(data);
      toast('Opened ' + file.name);
    } catch (e) {
      console.error(e);
      toast('Could not open ' + file.name + ': ' + e.message);
    }
  }

  // Formatting is measured from the live document, so view-only state
  // (zoom, page layout spacing) is suspended while it is read.
  async function withTrueLayout(fn) {
    const zoom = pageWrap.style.zoom;
    pageWrap.style.zoom = 1;
    Ink.unpaginate();
    try {
      return await fn();
    } finally {
      pageWrap.style.zoom = zoom;
      Ink.paginate();
    }
  }

  async function saveDocx() {
    try {
      const blob = await withTrueLayout(() => {
        const data = docData();
        delete data.html;
        return Docx.write(docEl, Object.assign(data, { author: Ink.options.author }));
      });
      download(blob, fileName('.docx'));
      toast('Saved ' + fileName('.docx'));
    } catch (e) {
      console.error(e);
      toast('Save failed: ' + e.message);
    }
  }

