  function currentCell() {
    const s = getSelection();
    return s.rangeCount ? closestIn(s.anchorNode, 'td,th') : null;
  }

  function newCell(colSpan) {
    const c = document.createElement('td');
    c.appendChild(document.createElement('br'));
    if (colSpan > 1) c.colSpan = colSpan;
    return c;
  }

  function insertRow(cell, below) {
    const row = cell.parentElement;
    const tr = document.createElement('tr');
    for (const c of row.cells) tr.appendChild(newCell(c.colSpan));
    row.parentNode.insertBefore(tr, below ? row.nextSibling : row);
    placeCaret(tr.cells[Math.min(cell.cellIndex, tr.cells.length - 1)]);
  }

  function insertColumn(cell, right) {
    const idx = cell.cellIndex;
    const table = cell.closest('table');
    for (const row of table.rows) {
      const ref = row.cells[Math.min(idx, row.cells.length - 1)];
      const c = newCell(1);
      if (!ref) row.appendChild(c);
      else row.insertBefore(c, right ? ref.nextSibling : ref);
    }
    const row = cell.parentElement;
    placeCaret(row.cells[right ? idx + 1 : idx]);
  }

  function removeTable(table) {
    let next = table.nextElementSibling;
    if (!next) { next = document.createElement('p'); next.innerHTML = '<br>'; table.after(next); }
    table.remove();
    placeCaret(next);
  }

  function deleteRow(cell) {
    const table = cell.closest('table');
    const row = cell.parentElement;
    const sibling = row.nextElementSibling || row.previousElementSibling;
    row.remove();
    if (!table.rows.length) removeTable(table);
    else placeCaret(sibling.cells[Math.min(cell.cellIndex, sibling.cells.length - 1)] || sibling.cells[0]);
  }

  function deleteColumn(cell) {
    const table = cell.closest('table');
    const idx = cell.cellIndex;
    for (const row of Array.from(table.rows)) {
      if (row.cells[idx]) row.cells[idx].remove();
      if (!row.cells.length) row.remove();
    }
    if (!table.rows.length) removeTable(table);
    else placeCaret(table.rows[0].cells[Math.max(0, Math.min(idx, table.rows[0].cells.length - 1))]);
  }

  function moveCell(cell, dir) {
    const cells = $$('td,th', cell.closest('table'));
    const i = cells.indexOf(cell) + dir;
    if (i < 0) return;
    if (i >= cells.length) {
      edit(() => insertRow(cell, true));
      return;
    }
    const r = document.createRange();
    r.selectNodeContents(cells[i]);
    setRange(r);
  }

